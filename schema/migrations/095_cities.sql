-- 095 : villes de livraison (communes du Cameroun) servies par GET /cities.
-- 315 communes rurales + 14 villes a arrondissements (Douala, Yaounde...) regroupees,
-- noms historiques de l'app gardes tels quels (Kousseri, Mballa). Source : Wikipedia
-- « Commune (Cameroun) » (360 communes, 2013). Les boutiques gardent le NOM de la
-- ville dans fastfoods.cities : un renommage est repercute par le backend
-- (PATCH /cities/:id), un retrait passe la ville en inactive (pas de suppression).
CREATE TABLE IF NOT EXISTS cities (
  id          BIGSERIAL PRIMARY KEY,
  name        TEXT NOT NULL UNIQUE,
  region      TEXT,
  active      BOOLEAN NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE cities ENABLE ROW LEVEL SECURITY;

